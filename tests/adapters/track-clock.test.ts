import { describe, expect, test } from 'vitest'
import { mainClockOffset, makeTrackClock } from '../../src/adapters/pose/track-clock'

/**
 * Часы видеодорожки против часов главного потока.
 *
 * Дефект, ради которого этот модуль есть, стоил целого живого прогона: кадры
 * с отметкой 934 628 373 мс пришли в забег, шедший по времени 29 131 мс, и
 * ядро прокрутило все девять раундов внутри одного тика. Снаружи это выглядело
 * как «игра зависла»: таймер стоит, кнопка паузы мертва, счёт ноль — при
 * исправных камере и трекере.
 */
describe('часы дорожки приведены к часам главного потока', () => {
  test('первый кадр задаёт поправку: отметка равна времени главного потока', () => {
    const c = makeTrackClock()

    expect(c.at(934_628_270, 29_131)).toBe(29_131)
  })

  test('дальше идут САМИ ЧАСЫ ДОРОЖКИ, а не момент обработки', () => {
    const c = makeTrackClock()
    c.at(934_628_270, 29_131)

    // Кадр снят через 83 мс по часам дорожки, а руки до него дошли на 40 мс
    // позже: отметкой обязана стать съёмка, иначе теряется дрожание тракта,
    // из которого считают задержку.
    expect(c.at(934_628_353, 29_254)).toBe(29_214)
  })

  test('два кадра из одной очереди не слипаются в одну отметку', () => {
    const c = makeTrackClock()
    c.at(1_000_000, 500)

    const a = c.at(1_000_083, 700)
    const b = c.at(1_000_166, 700)

    expect(a).not.toBe(b)
    expect(b - a).toBe(83)
  })

  test('дорожка без отметки — остаются свои часы', () => {
    const c = makeTrackClock()

    expect(c.at(null, 1_234)).toBe(1_234)
  })

  test('новая дорожка берёт поправку заново', () => {
    const c = makeTrackClock()
    c.at(934_628_270, 29_131)

    c.reset()

    expect(c.at(5_000, 60_000)).toBe(60_000)
  })

  test('отметка не уходит в будущее относительно часов главного потока', () => {
    const c = makeTrackClock()
    const now = 29_131

    // Кадр снят РАНЬШЕ, чем до него дошли руки, — иначе и не бывает.
    expect(c.at(934_628_270, now)).toBeLessThanOrEqual(now)
  })
})

/**
 * Часы воркера против часов главного потока.
 *
 * Знак этой поправки был обратным, и ошибка стоила бы второго провального
 * прогона: воркер поднимается в момент нажатия «Играть» (в журнале — 21 687
 * мс после загрузки), так что `now()` отставал от главных часов на 43 секунды.
 */
describe('часы воркера приведены к часам главного потока', () => {
  test('поправка ПОЛОЖИТЕЛЬНА: воркер начал отсчёт позже страницы', () => {
    expect(mainClockOffset(1_000, 22_700)).toBe(21_700)
  })

  test('поправка переводит время воркера ровно в главное', () => {
    const mainOrigin = 1_000
    const workerOrigin = 22_700
    const absolute = 1_000_000

    const workerNow = absolute - workerOrigin
    const mainNow = absolute - mainOrigin

    expect(workerNow + mainClockOffset(mainOrigin, workerOrigin)).toBe(mainNow)
  })

  test('воркер и страница с одним началом — поправки нет', () => {
    expect(mainClockOffset(5_000, 5_000)).toBe(0)
  })
})
