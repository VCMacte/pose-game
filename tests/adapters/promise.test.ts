/**
 * Срок на обещание — один сторож на проект.
 *
 * Он существует потому, что привилегированные обещания браузера способны не
 * завершиться НИКОГДА: разрешение камеры и микрофона, полный экран, замок
 * ориентации. Правило измерено в `run-game`, где без сроков приложение
 * вставало на экране загрузки, и перенесено сюда вместе с числами.
 *
 * До переезда в `src/adapters/promise.ts` эта функция жила приватной копией
 * внутри источника позы и не имела ни одного теста.
 */
import { describe, expect, test } from 'vitest'

import { withTimeout } from '../../src/adapters/promise'

describe('срок на обещание', () => {
  test('успевшее обещание проходит как есть', async () => {
    await expect(withTimeout(Promise.resolve(7), 1000, 'что-то')).resolves.toBe(7)
  })

  test('отказ обещания доходит наружу неизменным', async () => {
    // Сторож не превращает чужой отказ в свой: причина важна тому, кто её
    // показывает взрослому.
    await expect(withTimeout(Promise.reject(new Error('нет разрешения')), 1000, 'микрофон')).rejects.toThrow(
      'нет разрешения',
    )
  })

  test('молчащее обещание кончается отказом, и в нём НАЗВАНО что молчит', async () => {
    /*
     * Имя в сообщении — не украшение: отказ показывается взрослому на
     * служебном экране, и «нет ответа» без указания, от чего именно, не
     * говорит ему ничего.
     */
    await expect(withTimeout(new Promise(() => {}), 20, 'микрофон')).rejects.toThrow(/микрофон: нет ответа за 20 мс/)
  })

  test('успевшее обещание не оставляет таймер висеть', async () => {
    /*
     * Иначе node не выходит из прогона, пока срок не истечёт: тест на час
     * ожидания никто не заметит, а прогон встанет.
     */
    const started = Date.now()
    await withTimeout(Promise.resolve(1), 60_000, 'долгий срок')
    expect(Date.now() - started).toBeLessThan(1000)
  })
})
