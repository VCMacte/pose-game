/**
 * Множитель, которым настройка «строгость» масштабирует допуски.
 *
 * Масштабируются полуширины полос вокруг опорных значений: углы плеча,
 * предплечья, локтя и колена `straight`, полосы разноса ног ПО СТОПАМ
 * (`legs.ankle`), расстояния кистей и стопы у колена, а также отклонение от
 * средней линии корпуса у `front` (`shoulder.front` — он судит и плечо, и
 * предплечье, и кисти). НЕ масштабируются пороги-доказательства: ориентация
 * (она решает годность кадра, а не попадание), разница высот колен у опоры,
 * просадки и голос колена у приседа, `max` у ног и `horizontal` у наклона.
 * Иначе мягкий допуск налезал бы на соседнюю полосу и превращал уверенные
 * кадры в «не знаю».
 *
 * Полосы разноса ног ПО КОЛЕНЯМ (`legs.knee`) не масштабируются по той же
 * причине, что `max`: это не допуск вокруг цели, а порог-доказательство —
 * разнос колен заново выводит ненаблюдаемый разнос стоп. Строгость же —
 * родительская настройка «насколько точно ребёнок обязан повторить позу», и
 * масштабировать ею вывод было бы подменой смысла. Цена подмены измерима:
 * зазоры там 0.05 / 0.04 / 0.02 S, и мягкий ×1.3 съедал бы их целиком —
 * `shoulder` дотягивался бы до 1.921 при `wide` от 1.922, то есть широкая
 * стойка на 1.92 читалась бы уверенным `shoulder`. Это ПРОМАХ там, где норма
 * честно отвечает «не знаю», и промах не по вине ребёнка: оба приседа требуют
 * `legs: wide`.
 */
export function strictness(level: 'soft' | 'normal' | 'strict'): number {
  return CONFIG.strictness[level]
}
