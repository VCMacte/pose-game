import { AXES, type Axis, type AxisReadings, type MeasuredBy } from './axes'
import type { PoseSpec } from './types'

/**
 * Совпадение ОДНОГО кадра с позой. Голосование по окну кадров — не здесь
 * (`judge.ts`, окно 600 мс со сдвигом на задержку).
 *
 * Читать вместе с docs/judging.md («Правило приговора») и
 * docs/poses-and-figure.md («Девять осей»). Четыре правила держат файл:
 *
 * - **Проверяются только оси из `spec.requires`.** Ось, которой поза не
 *   требует, не судится вовсе и в журнал не попадает: это уже заложено в
 *   данных — каждая поза перечисляет свои оси сама.
 * - **Ориентация — НЕ ось совпадения.** Кадр не с той ориентацией НЕВАЛИДЕН
 *   (причина отказа присутствия, `presence.ts`), а не промахнулся: повернув
 *   «Букву Т» в профиль, плечи `side` сохранить нельзя — руки в стороны в
 *   профиль смотрят в камеру, и «промах ровно по ориентации» физически
 *   невыразим. Поэтому ось пропускается явно, даже окажись она в требованиях.
 * - **«Не знаю» по требуемой оси — не совпадение,** но и не промах по
 *   существу: взрослый, читающий журнал, обязан видеть разницу между «ребёнок
 *   сделал не то» и «игра не смогла измерить». Её несёт `outcome`.
 * - **`measured` уходит в журнал как есть,** включая `NaN` и `measuredBy`:
 *   контракт `AxisReading` установлен в `axes.ts`, и размывать его здесь
 *   нельзя. По этому полю взрослый читает «левое плечо 58° при цели 90±30», не
 *   переигрывая раунд с ребёнком.
 */

/**
 * Чем кончилась ось.
 *
 * - `ok` — состояние совпало с требуемым.
 * - `miss` — состояние ИЗМЕРЕНО и оно другое: ребёнок сделал не то.
 * - `unmeasured` — ось ответила «не знаю»: игра измерить не смогла. Не
 *   совпадение, но и не вина ребёнка — различать обязательно.
 * - `excused` — то же «не знаю», но объяснимое перекрытием: дальняя
 *   конечность в профильной позе. Из приговора исключается, см. ниже.
 */
export type AxisOutcome = 'ok' | 'miss' | 'unmeasured' | 'excused'

/** Приговор по одной оси — строка журнала `round.judge.perAxis`. */
export type AxisVerdict = {
  /** Требуемое состояние, строкой: журнал читает человек. */
  want: string
  /** Измеренное состояние, либо `unknown`. */
  got: string
  /** Измеренное значение оси в её собственных единицах; `NaN` — мерить было нечем. */
  measured: number
  /** Чем измерено, если ось умеет мерить по-разному (сейчас такая одна — ноги). */
  measuredBy?: MeasuredBy
  /** Засчитана ли ось. `false` и у `excused`: не совпала, но приговор не ронит. */
  ok: boolean
  outcome: AxisOutcome
}

/** Приговор по кадру: совпал ли и что вышло по каждой требуемой оси. */
export type FrameMatch = {
  matched: boolean
  perAxis: Partial<Record<Axis, AxisVerdict>>
}

/**
 * Можно ли списать «не знаю» этой оси на перекрытие телом.
 *
 * Только дальняя конечность и только в профильной позе. В профиль дальняя рука
 * закрыта корпусом — это свойство САМОЙ позы, которую игра и попросила
 * показать, а не случайность: без оправдания профильные позы не засчитывались
 * бы никогда, и ребёнок делал бы их правильно, не получая ничего.
 *
 * Ближняя сторона обращена К камере, и её пропажа — именно случайность (ребёнок
 * ушёл из кадра, свет), поэтому оправданию не подлежит. Заодно этим закрыта
 * дыра: при невидимой голове не разрешается направление взгляда, и ближняя с
 * дальней сторонами обе становятся «не знаю» — оправдай тут обе, и кадр с
 * невидимыми руками засчитывался бы по одним ногам.
 */
const occluded = (spec: PoseSpec, axis: Axis): boolean =>
  spec.orientation === 'profile' && axis.startsWith('far')

/**
 * Совпадение кадра с позой: все требуемые оси обязаны совпасть.
 *
 * `r` — показания того же кадра из `axes()`. Кадра без скелета здесь не бывает:
 * путь к показаниям идёт через `geometry()`, которая негодный кадр уже
 * отвергла, поэтому ветки «нет скелета» у `matchFrame` нет.
 */
export function matchFrame(spec: PoseSpec, r: AxisReadings): FrameMatch {
  const perAxis: Partial<Record<Axis, AxisVerdict>> = {}
  let matched = true

  for (const axis of AXES) {
    // Ориентация — ось показаний, но не ось совпадения: её судит присутствие.
    if (axis === 'orientation') continue
    const want: unknown = spec.requires[axis]
    if (want === undefined) continue

    const { state, measured, measuredBy } = r[axis]
    const got: unknown = state
    const outcome: AxisOutcome =
      got === want
        ? 'ok'
        : got !== 'unknown'
          ? 'miss'
          : // «Не знаю» из-за видимости узнаётся по `measured`: `NaN` значит,
            // что мерить было нечем. Значение, попавшее в зазор между
            // состояниями, измерено — перекрытием его не объяснить.
            occluded(spec, axis) && !Number.isFinite(measured)
            ? 'excused'
            : 'unmeasured'

    if (outcome !== 'ok' && outcome !== 'excused') matched = false
    perAxis[axis] = {
      want: String(want),
      got: String(got),
      measured,
      ...(measuredBy === undefined ? {} : { measuredBy }),
      ok: outcome === 'ok',
      outcome,
    }
  }

  return { matched, perAxis }
}
