/**
 * Срок на обещание.
 *
 * Живёт отдельным файлом, а не копией в каждом адаптере: срок нужен и
 * конвейерам позы, и привилегированным обещаниям браузера (полный экран,
 * замок ориентации), а две копии одного сторожа однажды разойдутся числами.
 */

/**
 * То же обещание, но с отказом по сроку.
 *
 * **Привилегированные обещания браузера могут не завершиться НИКОГДА** —
 * измерено в `run-game`: без срока приложение вставало на экране загрузки,
 * ожидая разрешения, полного экрана или ориентации. Поэтому ждать их без
 * срока нельзя нигде.
 */
export function withTimeout<T>(p: Promise<T>, ms: number, what: string): Promise<T> {
  return new Promise<T>((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error(`${what}: нет ответа за ${ms} мс`)), ms)
    p.then(
      (v) => {
        clearTimeout(timer)
        resolve(v)
      },
      (e) => {
        clearTimeout(timer)
        reject(e)
      },
    )
  })
}
