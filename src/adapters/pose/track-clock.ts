/**
 * Часы ВИДЕОДОРОЖКИ, приведённые к часам главного потока.
 *
 * `VideoFrame.timestamp` отсчитывается не от `performance.timeOrigin`, а от
 * собственного начала дорожки, и разрыв достигает суток. В первом живом
 * прогоне на телефоне кадры пришли с отметкой 934 628 373 мс при времени
 * забега 29 131 мс — и ядро, которому отметка кадра двигает раунды, прокрутило
 * весь 60-секундный забег внутри ОДНОГО тика: 142 мс настенного времени,
 * девять несудимых раундов с пустым буфером, счёт ноль. Камера и трекер при
 * этом работали исправно (51 fps, инференс 68 мс).
 *
 * Поправка снимается ОДИН раз на дорожку, а не берётся `now()` на каждом
 * кадре. Разница существенна: `now()` — это момент, когда до кадра дошли руки,
 * и очередь из двух кадров получила бы одинаковые отметки, потеряв дрожание
 * съёмки, из которого и считается задержка тракта.
 *
 * → `docs/camera-and-pose.md`
 */
export interface TrackClock {
  /**
   * Отметка кадра на часах главного потока.
   *
   * @param tTrackMs отметка дорожки в миллисекундах, `null` — дорожка её не дала
   * @param nowMs текущее время НА ЧАСАХ ГЛАВНОГО ПОТОКА
   */
  at(tTrackMs: number | null, nowMs: number): number
  /** Новая дорожка — новое начало отсчёта, прежняя поправка к нему не относится. */
  reset(): void
}

export function makeTrackClock(): TrackClock {
  /** `null` — дорожки ещё не было: первый её кадр и задаёт поправку. */
  let offset: number | null = null

  return {
    at(tTrackMs, nowMs) {
      // Дорожка отметки не дала — остаются только свои часы. Лгать о точности
      // тут нечем, зато шкала верная, а она и важнее.
      if (tTrackMs === null) return nowMs
      offset ??= nowMs - tTrackMs
      return tTrackMs + offset
    },
    reset() {
      offset = null
    },
  }
}

/**
 * Поправка, приводящая часы ВОРКЕРА к часам главного потока.
 *
 * У воркера своё начало отсчёта — момент его создания, то есть ПОЗЖЕ начала
 * страницы. Вывод в одну строчку: абсолютный момент один и тот же, значит
 *
 * ```
 * workerNow + workerOrigin === mainNow + mainOrigin
 * mainNow === workerNow + (workerOrigin − mainOrigin)
 * ```
 *
 * — поправка равна `workerOrigin − mainOrigin` и **положительна**.
 *
 * Знак здесь был обратным, и это не мелочь арифметики. Воркер создаётся не при
 * загрузке страницы, а когда ребёнок нажал «Играть»: в журнале первого живого
 * прогона `pose.boot` стоит на 21 687 мс. При обратном знаке `now()` отставал
 * от главных часов на ДВЕ такие задержки — 43 секунды, — и кадр, датированный
 * им, не попадал в окно судейства никогда. Снаружи это неотличимо от дефекта,
 * ради которого написан `TrackClock`: раунды с пустым буфером и счёт ноль.
 *
 * → `docs/camera-and-pose.md`
 */
export function mainClockOffset(mainTimeOrigin: number, workerTimeOrigin: number): number {
  return workerTimeOrigin - mainTimeOrigin
}
