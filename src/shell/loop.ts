/**
 * Два независимых такта: кадры камеры и кадры экрана.
 *
 * **Кадр камеры НЕ рисует, кадр экрана НЕ трогает трекер.** Это главный
 * инвариант покадрового пути, и он проверяется тестом. Склеенные такты дают
 * ровно ту болезнь, от которой лестница конвейеров и спасает: 11 Гц поз
 * превращаются в 11 Гц картинки, а стена едет рывками. Обратная склейка хуже:
 * рендер начинает ждать инференс, и просадка GPU останавливает мир.
 *
 * Поэтому здесь:
 *
 * - `onSample` только КЛАДЁТ кадр в буфер и считает статистику;
 * - `frame(t)` забирает накопленное, продвигает мир и рисует.
 *
 * Разбор: `docs/camera-and-pose.md`, `docs/render-and-layout.md`.
 */

import type { Frame } from '../core/types'
import { health } from '../adapters/log/events'
import { write as journalWrite } from '../adapters/log/store'
import type { LogEvent } from '../adapters/log/store'

/** Раз в сколько писать сводку здоровья в журнал. */
const HEALTH_MS = 1000

/**
 * Самый большой шаг ИГРОВОГО времени за один кадр экрана.
 *
 * Страница замирает от внешних причин — звонок, будильник, свёрнутое
 * приложение, — и такт экрана в это время не вызывается вовсе. Потом приходит
 * ОДИН кадр с разрывом в десятки секунд, и ядро закрывает в этом тике все
 * раунды, чьё время вышло: забег кончается мгновенно. Это ровно то, что
 * случилось в живом прогоне 21.10.2026 от других часов, и ровно тот класс
 * отказа, который снаружи читается как три разных дефекта.
 *
 * Приём перенесён из `run-game` (`js/train.js:620-628`), где он измерен
 * вживую: будильник 14.10 не сдвинул забег ни на шаг — «забег вперёд не
 * перескочит, замершая страница продолжится с того же места».
 *
 * **Число здесь НЕ их пятьдесят миллисекунд, и это важно.** У них зажимается
 * `dt`, которым интегрируется движение, и пятьдесят — пол при 20 fps. У нас
 * зажимается РАСПИСАНИЕ забега, и слишком тесный зажим замедлил бы игру на
 * медленном устройстве: кадр экрана длиннее зажима означал бы, что игровое
 * время идёт медленнее настоящего, и забег на 60 секунд тянулся бы сотню.
 * Поймано тестом калибровки, где такт идёт с шагом 83 мс.
 *
 * 250 мс выбраны так, чтобы зажим не срабатывал ни на одном настоящем кадре
 * (на телефоне измерено 51–56 fps, худшее окно инференса около 105 мс) и всё
 * же оставался заметно короче окна судейства (600 мс) — то есть внутри окна
 * по-прежнему несколько тиков.
 *
 * Пауза вместо зажима здесь НЕ ставится: случившееся скрытие страницы должно
 * быть видно в журнале (`visibility`), а не замаскировано паузой, которой
 * никто не просил.
 * → `docs/presence-and-pause.md`
 */
export const MAX_STEP_MS = 250

/** Что продвижение мира успело насчитать за кадр — для сводки `health`. */
export type StepCounts = { valid: number; lost: number }

export type LoopOpts = {
  /**
   * Продвинуть мир накопленными кадрами и нарисовать его. Возвращает, сколько
   * кадров присутствие признало годными и сколько потеряло: эти числа знает
   * только ядро, и выдумывать их здесь было бы враньём в журнал.
   */
  step(t: number, frames: Frame[]): StepCounts | void
  /**
   * Куда писать сводку здоровья. По умолчанию — журнал приложения.
   *
   * Подменяется, чтобы частоту записи можно было ПРОВЕРИТЬ: в node журнал
   * молчит (IndexedDB нет), и тест, не подменяющий запись, не отличает «раз в
   * секунду» от «не пишем вовсе».
   */
  write?: (e: LogEvent) => void
}

export type Loop = {
  /**
   * Кадр камеры. Только буфер и счётчики: ни рендера, ни продвижения мира.
   * Зовётся из `onSample` источника позы.
   */
  sample(f: Frame): void
  /**
   * Сводка от источника позы (`beat`): задержки инференса и отбросы. Приходит
   * оттуда, а не считается здесь, потому что инференс идёт в воркере и главный
   * поток о его длительности знает только по сообщению.
   */
  noteBeat(b: { p50: number; p95: number; dropped: number }): void
  /**
   * Кадр экрана. Забирает накопленные кадры и отдаёт их `step`. Зовётся из
   * `requestAnimationFrame`.
   */
  frame(t: number): void
  /** Сколько кадров сейчас ждут в буфере — для отладки. */
  pending(): number
}

export function makeLoop(opts: LoopOpts): Loop {
  const write = opts.write ?? journalWrite
  let buf: Frame[] = []
  let draws = 0
  let valid = 0
  let lost = 0
  let drops = 0
  let p50 = 0
  let p95 = 0
  let lastHealth = 0
  let started = false
  /** Отметка предыдущего кадра экрана в НАСТОЯЩИХ часах. */
  let lastReal = 0
  /**
   * Игровое время: то, что уходит в ядро. Отстаёт от настоящего на всё, что
   * съел зажим `MAX_STEP_MS`.
   */
  let gameT = 0
  /**
   * Насколько игровое время отстало от настоящего. Им переводятся отметки
   * КАДРОВ: ядро сравнивает время кадра со временем тика, и две шкалы здесь
   * разъехаться не вправе — это и есть дефект 21.10.
   */
  let skew = 0

  return {
    sample: (f) => {
      /*
       * Буфер, а не «последний кадр»: судейство голосует по ВСЕМ кадрам окна, и
       * выброшенный кадр — это выброшенный голос. Потолка здесь нет намеренно:
       * его роль играет `frame`, который забирает буфер целиком каждый кадр
       * экрана. Рендер идёт в 38–40 fps против 11 Гц поз, так что в буфере
       * лежит один-два кадра, а не очередь.
       *
       * Кадр переводится в ИГРОВОЕ время здесь, отставанием НА МОМЕНТ ПРИХОДА,
       * а не текущим при разборе буфера. Разница принципиальна: кадр, пришедший
       * до разрыва, при сдвиге «текущим» отставанием уехал бы в прошлое — и
       * `run.tick` бросил бы «время идёт назад», потому что для него это
       * всегда дефект оболочки. А кадр, пришедший ВО ВРЕМЯ разрыва, окажется
       * впереди игрового времени, и его зажмёт уже существующий кламп ядра
       * (`f.t > t ? t : f.t`) — то есть он прочтётся как «только что», что и
       * есть правда о нём.
       */
      const t = skew === 0 ? f.t : f.t - skew

      /*
       * Кадры, накопившиеся ЗА время замирания, отбрасываются. Конвейеры позы
       * не живут на `requestAnimationFrame` — воркер и цепочка таймаутов
       * продолжают слать кадры скрытой странице, — и без отбора все они
       * пришли бы одним тиком, зажались ядром в ОДНУ отметку и перевесили бы
       * голосование: сотни кадров против обычных семи, снятых тогда, когда
       * игра не показывала ребёнку ничего. Это ровно «приговор за то, чего
       * игра не видела», и бюджет журнала такой всплеск тоже съел бы.
       *
       * Порог — тот же `MAX_STEP_MS`: кадр, обогнавший последний тик больше
       * чем на один зажатый шаг, принадлежит остановке, а не игре. До первого
       * тика сравнивать не с чем, и тогда берутся все.
       */
      if (started && t > gameT + MAX_STEP_MS) return

      buf.push(t === f.t ? f : { ...f, t })
    },
    noteBeat: (b) => {
      p50 = b.p50
      p95 = b.p95
      drops += b.dropped
    },
    frame: (t) => {
      if (!started) {
        started = true
        lastHealth = t
        lastReal = t
        gameT = t
      }

      /*
       * Игровое время продвигается ЗАЖАТЫМ шагом — см. `MAX_STEP_MS`. Шаг
       * считается по настоящим часам, а отставание накапливается в `skew`:
       * им переводятся отметки кадров, иначе шкала тика и шкала кадра
       * разъедутся.
       */
      gameT += Math.min(Math.max(0, t - lastReal), MAX_STEP_MS)
      lastReal = t
      skew = t - gameT

      const frames = buf
      buf = []
      draws++

      const got = opts.step(gameT, frames)
      if (got) {
        valid += got.valid
        lost += got.lost
      }

      if (t - lastHealth >= HEALTH_MS) {
        const sec = (t - lastHealth) / 1000
        write(
          health({
            fps: Math.round(draws / sec),
            inferP50: p50,
            inferP95: p95,
            drops,
            valid,
            lost,
          }),
        )
        draws = 0
        valid = 0
        lost = 0
        drops = 0
        lastHealth = t
      }
    },
    pending: () => buf.length,
  }
}
